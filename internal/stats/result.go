// Package stats хранит исход запросов и агрегированные метрики прогона.
package stats

import "time"

// Result это исход одного запроса. Воркеры пишут такие значения в канал, а
// коллектор их агрегирует. Ошибка запроса это данные, а не авария:
// транспортный сбой оседает в поле Err и не роняет прогон.
type Result struct {
	Latency time.Duration // сколько занял запрос: от отправки до полного чтения тела
	Status  int           // HTTP-код ответа; 0, если ответа не было
	Err     error         // транспортная ошибка (dial/timeout/reset), nil если ответ пришёл
}
